"""Generate the ASCII bitmap fonts used by the SSD1315 UI.

Rendered once with Pillow from a system monospace font and committed as C
tables, so the firmware build does not depend on Pillow or on the host's fonts.

Layout: column-major, bit 0 = top row -- exactly what the SSD1306 page buffer
wants. 6x8 glyph = 6 bytes (1 page), 8x16 glyph = 8 columns x 2 pages.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

FONT_CANDIDATES = [
    r"C:\Windows\Fonts\consola.ttf",
    r"C:\Windows\Fonts\consolab.ttf",
    r"C:\Windows\Fonts\cour.ttf",
    r"C:\Windows\Fonts\lucon.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
]

FIRST = 0x20
LAST = 0x7E


def load_font(size):
    for path in FONT_CANDIDATES:
        if os.path.exists(path):
            try:
                return ImageFont.truetype(path, size), path
            except OSError:
                continue
    raise SystemExit("no usable monospace font found")


def render(ch, cell_w, cell_h, size):
    font, _ = load_font(size)
    img = Image.new("L", (cell_w, cell_h), 0)
    draw = ImageDraw.Draw(img)
    bbox = draw.textbbox((0, 0), ch, font=font)
    glyph_h = bbox[3] - bbox[1]
    y = (cell_h - glyph_h) // 2 - bbox[1]
    x = 1 if cell_w >= 6 else 0
    draw.text((x, y), ch, font=font, fill=255)
    return img


def to_columns(img, pages):
    w, h = img.size
    pixels = img.load()
    out = []
    for x in range(w):
        col = []
        for page in range(pages):
            bits = 0
            for bit in range(8):
                y = page * 8 + bit
                if y < h and pixels[x, y] > 96:
                    bits |= 1 << bit
            col.append(bits)
        out.append(col)
    return out


def emit(name, cell_w, cell_h, size, path, header_path):
    pages = (cell_h + 7) // 8
    glyphs = []
    for code in range(FIRST, LAST + 1):
        glyphs.append(to_columns(render(chr(code), cell_w, cell_h, size), pages))

    lines = ["/* Generated by tools/gen_font.py -- do not edit by hand. */",
             '#include "%s"' % os.path.basename(header_path),
             "",
             "const uint8_t %s[%d][%d][%d] = {" % (name, LAST - FIRST + 1, cell_w, pages)]
    for idx, glyph in enumerate(glyphs):
        cols = ", ".join("{" + ", ".join("0x%02X" % b for b in col) + "}" for col in glyph)
        lines.append("    { %s }, /* 0x%02X */" % (cols, FIRST + idx))
    lines.append("};")
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")

    guard = "SC_" + name.upper() + "_H"
    with open(header_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("#pragma once\n\n#include <stdint.h>\n\n")
        handle.write("/* %dx%d ASCII font, characters 0x%02X..0x%02X, column-major bytes.\n"
                     " * Bit 0 of a column byte is the top scan line of that page. */\n"
                     % (cell_w, cell_h, FIRST, LAST))
        handle.write("extern const uint8_t %s[%d][%d][%d];\n" % (name, LAST - FIRST + 1, cell_w, pages))
    return glyphs, pages


def preview(glyphs, pages, cell_w, cell_h, text):
    art = []
    for page in range(pages):
        for bit in range(8):
            row = ""
            for ch in text:
                idx = ord(ch) - FIRST
                if idx < 0 or idx >= len(glyphs):
                    idx = ord("?") - FIRST
                for x in range(cell_w):
                    row += "#" if glyphs[idx][x][page] & (1 << bit) else "."
            art.append(row)
    return "\n".join(art)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "main", "ui")
    os.makedirs(out, exist_ok=True)

    g6, p6 = emit("sc_font6x8_bits", 6, 8, 8,
                  os.path.join(out, "font6x8.c"), os.path.join(out, "font6x8.h"))
    g8, p8 = emit("sc_font8x16_bits", 8, 16, 15,
                  os.path.join(out, "font8x16.c"), os.path.join(out, "font8x16.h"))

    print(preview(g6, p6, 6, 8, "StatusCast 87%"))
    print()
    print(preview(g8, p8, 8, 16, "PS5 on"))


if __name__ == "__main__":
    main()
